"""Database access for SQLite (local) and PostgreSQL (production).

The survey app uses a deliberately small subset of SQL, so one adapter is
enough. The differences that matter are:

* SQLite uses ``?`` placeholders, PostgreSQL uses ``%s``.
* SQLite returns a new row's id as ``cursor.lastrowid``; PostgreSQL uses
  ``INSERT ... RETURNING id``.
* The identity column is declared differently in each dialect.

Everything else (text columns, integer flags, ISO-8601 timestamps stored as
text) is portable, so the routes do not need to know which database is in use.
"""

from __future__ import annotations

import secrets
import sqlite3
from typing import Any, Mapping
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

try:  # psycopg is only required when DATABASE_URL is set
    import psycopg
    from psycopg.rows import dict_row

    _PSYCOPG_ERROR = psycopg.Error
    _PSYCOPG_AVAILABLE = True
except ImportError:  # local SQLite installs do not need the driver
    psycopg = None  # type: ignore[assignment]
    dict_row = None  # type: ignore[assignment]
    _PSYCOPG_ERROR = None
    _PSYCOPG_AVAILABLE = False

# ``except storage.StorageError`` works for whichever driver is active.
StorageError = (
    (sqlite3.Error,)
    if _PSYCOPG_ERROR is None
    else (sqlite3.Error, _PSYCOPG_ERROR)
)

COLUMNS = (
    "code",
    "created_at",
    "consent",
    "sector",
    "years",
    "employees",
    "role",
    "location",
    "channels",
    "answers",
    "duration_seconds",
    "open_challenge",
)

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS responses (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    code             TEXT UNIQUE NOT NULL,
    created_at       TEXT NOT NULL,
    consent          INTEGER NOT NULL DEFAULT 0,
    sector           TEXT NOT NULL,
    years            TEXT NOT NULL,
    employees        TEXT NOT NULL,
    role             TEXT NOT NULL,
    location         TEXT NOT NULL,
    channels         TEXT NOT NULL,
    answers          TEXT NOT NULL,
    duration_seconds INTEGER,
    open_challenge   TEXT
);
CREATE INDEX IF NOT EXISTS idx_responses_created
    ON responses (created_at);
"""

POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS responses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             TEXT UNIQUE NOT NULL,
    created_at       TEXT NOT NULL,
    consent          INTEGER NOT NULL DEFAULT 0,
    sector           TEXT NOT NULL,
    years            TEXT NOT NULL,
    employees        TEXT NOT NULL,
    role             TEXT NOT NULL,
    location         TEXT NOT NULL,
    channels         TEXT NOT NULL,
    answers          TEXT NOT NULL,
    duration_seconds INTEGER,
    open_challenge   TEXT
);
CREATE INDEX IF NOT EXISTS idx_responses_created
    ON responses (created_at);
"""


# Parameters added by ORMs/poolers that libpq does not understand. Supabase's
# dashboard sometimes includes them in the copied connection string.
UNSUPPORTED_QUERY = {
    "pgbouncer",
    "connection_limit",
    "pool_timeout",
    "statement_cache_size",
    "schema",
}


def normalise_url(url: str) -> str:
    """Make a provider connection string safe for psycopg/libpq.

    * Accepts the ``postgres://`` prefix used by some providers.
    * Removes ORM/pooler-only query parameters such as ``pgbouncer=true``;
      libpq rejects unknown parameters.
    * Adds ``sslmode=require`` for Supabase hosts when it is missing.
    """
    if not url:
        return ""
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://") :]
    try:
        parts = urlsplit(url)
        query = [
            (key, value)
            for key, value in parse_qsl(parts.query, keep_blank_values=True)
            if key.lower() not in UNSUPPORTED_QUERY
        ]
        host = (parts.hostname or "").lower()
        has_sslmode = any(key.lower() == "sslmode" for key, _ in query)
        if "supabase." in host and not has_sslmode:
            query.append(("sslmode", "require"))
        return urlunsplit(
            (parts.scheme, parts.netloc, parts.path, urlencode(query), parts.fragment)
        )
    except ValueError:
        # Let psycopg produce the detailed connection-string error.
        return url


def database_label(url: str) -> str:
    """Describe a connection URL without exposing its password."""
    try:
        parts = urlsplit(normalise_url(url))
        host = parts.hostname or "?"
        name = (parts.path or "/").lstrip("/") or "?"
        return f"{host}/{name}"
    except ValueError:
        return "configured"


class SQLiteConnection:
    backend = "sqlite"

    def __init__(self, path: str) -> None:
        self._conn = sqlite3.connect(path, timeout=15)
        self._conn.row_factory = sqlite3.Row
        self._conn.execute("PRAGMA journal_mode=WAL")
        self._conn.execute("PRAGMA foreign_keys=ON")

    def execute(self, sql: str, params: tuple = ()) -> sqlite3.Cursor:
        return self._conn.execute(sql, params)

    def executescript(self, script: str) -> None:
        self._conn.executescript(script)

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()


class PostgresConnection:
    backend = "postgres"

    def __init__(self, url: str) -> None:
        if not _PSYCOPG_AVAILABLE:
            raise RuntimeError(
                "DATABASE_URL is set but psycopg is not installed. "
                "Add 'psycopg[binary]' to requirements.txt."
            )
        self._conn = psycopg.connect(
            normalise_url(url),
            row_factory=dict_row,
            connect_timeout=10,
            # Supabase's transaction pooler (port 6543) cannot keep named
            # prepared statements between transactions. Disabling them is
            # harmless on a direct/session connection and required here.
            prepare_threshold=None,
        )

    def execute(self, sql: str, params: tuple = ()):
        # Every query in this app uses positional placeholders; none contains
        # a literal '?' or '%' that would need escaping.
        return self._conn.execute(sql.replace("?", "%s"), params)

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            statement = statement.strip()
            if statement:
                self._conn.execute(statement)

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()


def connect(backend: str, db_path: str, database_url: str):
    if backend == "postgres":
        return PostgresConnection(database_url)
    return SQLiteConnection(db_path)


def init_schema(conn) -> None:
    conn.executescript(
        POSTGRES_SCHEMA if conn.backend == "postgres" else SQLITE_SCHEMA
    )


def insert_response(conn, values: Mapping[str, Any]) -> int:
    """Insert one response and return its numeric id.

    A unique temporary code is used because ``code`` is ``NOT NULL UNIQUE``
    and the final code is derived from the id only after the insert. This
    also keeps concurrent submissions from colliding on an empty string.
    """
    missing = set(COLUMNS) - {"code"} - set(values)
    if missing:
        raise ValueError(f"missing response columns: {sorted(missing)}")

    record = {"code": f"TMP-{secrets.token_hex(12)}", **values}
    params = tuple(record[column] for column in COLUMNS)
    columns = ", ".join(COLUMNS)
    if conn.backend == "postgres":
        placeholders = ", ".join(["%s"] * len(COLUMNS))
        sql = (
            f"INSERT INTO responses ({columns}) VALUES ({placeholders}) "
            "RETURNING id"
        )
        row = conn.execute(sql, params).fetchone()
        return int(row["id"])

    placeholders = ", ".join(["?"] * len(COLUMNS))
    sql = f"INSERT INTO responses ({columns}) VALUES ({placeholders})"
    return int(conn.execute(sql, params).lastrowid)


def set_code(conn, response_id: int, code: str) -> None:
    conn.execute(
        "UPDATE responses SET code = ? WHERE id = ?",
        (code, response_id),
    )
